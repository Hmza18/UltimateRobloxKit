#!/usr/bin/env python3
"""Convert make-anim exports (out/<Name>.json + .rbxmx) into the cinematic's clip data.

    python3 tools/clips_to_luau.py <make-anim out dir>

Writes src/ReplicatedStorage/SupermarketCinematics/AnimationDefinitions/Clips/<Name>.luau (compact
per-joint tracks: times + quaternion [+ position for the root joint]) and copies the KeyframeSequence
to animations/<Name>.rbxmx for uploading. Stdlib only; runs on Python 3.9+.

Every exported pose uses Linear easing (the pose scripts sample every 2 frames and the exporter bakes
anything else), so the runtime reproduces Roblox's own playback with a slerp between keys.
"""
import json
import math
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
CLIPS = HERE / "src/ReplicatedStorage/SupermarketCinematics/AnimationDefinitions/Clips"
ANIMS = HERE / "animations"


def quat(r):
    """Rotation matrix (row-major 3x3, CFrame R00..R22) -> (x, y, z, w)."""
    m00, m01, m02, m10, m11, m12, m20, m21, m22 = r
    tr = m00 + m11 + m22
    if tr > 0:
        s = math.sqrt(tr + 1.0) * 2
        w, x, y, z = 0.25 * s, (m21 - m12) / s, (m02 - m20) / s, (m10 - m01) / s
    elif m00 > m11 and m00 > m22:
        s = math.sqrt(1.0 + m00 - m11 - m22) * 2
        w, x, y, z = (m21 - m12) / s, 0.25 * s, (m01 + m10) / s, (m02 + m20) / s
    elif m11 > m22:
        s = math.sqrt(1.0 + m11 - m00 - m22) * 2
        w, x, y, z = (m02 - m20) / s, (m01 + m10) / s, 0.25 * s, (m12 + m21) / s
    else:
        s = math.sqrt(1.0 + m22 - m00 - m11) * 2
        w, x, y, z = (m10 - m01) / s, (m02 + m20) / s, (m12 + m21) / s, 0.25 * s
    if w < 0:
        x, y, z, w = -x, -y, -z, -w
    return x, y, z, w


def num(v, nd=4):
    s = f"{v:.{nd}f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def convert(data):
    """Clip JSON -> (lua text, summary dict)."""
    joints = {}
    for k in data["keyframes"]:
        for joint, pose in k["poses"].items():
            joints.setdefault(joint, []).append((k["time"], pose["cf"]))
    lines = ["-- Generated by tools/clips_to_luau.py from make-anim's export of anim_src/%s.py. Do not edit." % data["name"],
             "-- Method by fwjelaa (FWJ STUDIOS). Times in seconds; q = quaternion x,y,z,w per key; p = position (root joint only).",
             "return {",
             '\tname = "%s",' % data["name"],
             "\tlength = %s," % num(data["length"] / data["fps"], 5),
             "\tloop = %s," % ("true" if data["loop"] else "false"),
             '\tpriority = "%s",' % data["priority"],
             "\tmarkers = {"]
    for k in data["keyframes"]:
        for name, _ in k["markers"]:
            lines.append('\t\t{ t = %s, name = "%s" },' % (num(k["time"], 5), name))
    lines.append("\t},")
    lines.append("\ttracks = {")
    for joint in sorted(joints):
        keys = sorted(joints[joint])
        times = ", ".join(num(t, 5) for t, _ in keys)
        qs = ", ".join(", ".join(num(c) for c in quat(cf[3:])) for _, cf in keys)
        moves = any(abs(c) > 1e-5 for _, cf in keys for c in cf[:3])
        lines.append("\t\t%s = {" % joint)
        lines.append("\t\t\tt = { %s }," % times)
        lines.append("\t\t\tq = { %s }," % qs)
        if moves:
            lines.append("\t\t\tp = { %s }," % ", ".join(", ".join(num(c) for c in cf[:3]) for _, cf in keys))
        lines.append("\t\t},")
    lines.append("\t},")
    lines.append("}")
    return "\n".join(lines) + "\n", {"joints": len(joints), "keys": len(data["keyframes"])}


def main(argv):
    if len(argv) != 2:
        sys.exit(__doc__)
    out = Path(argv[1])
    CLIPS.mkdir(parents=True, exist_ok=True)
    ANIMS.mkdir(parents=True, exist_ok=True)
    names = []
    for src in sorted(out.glob("SM_*.json")):
        data = json.loads(src.read_text(encoding="utf-8"))
        text, info = convert(data)
        (CLIPS / f"{data['name']}.luau").write_text(text, encoding="utf-8", newline="\n")
        rbxmx = src.with_suffix(".rbxmx")
        if rbxmx.exists():
            shutil.copyfile(rbxmx, ANIMS / rbxmx.name)
        names.append(data["name"])
        print(f"{data['name']}: {info['keys']} keys, {info['joints']} joints, {len(text) // 1024} KB")
    if not names:
        sys.exit(f"no SM_*.json exports in {out}")


if __name__ == "__main__":
    main(sys.argv)
