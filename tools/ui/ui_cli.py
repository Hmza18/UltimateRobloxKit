#!/usr/bin/env python3
"""`urk.py ui ...`: create, validate, preview and install screen specs.

  python3 urk.py ui list                                      # built-in screens with descriptions
  python3 urk.py ui new PetSimShop --name MyShop --project ~/games/MyGame
  python3 urk.py ui validate path/to/MyShop.json [more.json]
  python3 urk.py ui preview path/to/MyShop.json [-o out.html] [--open]
  python3 urk.py ui tokens [--check]                          # regenerate StyleTokens.luau
  python3 urk.py ui extract reference.png                     # palette, outline, layout hints for a spec
  python3 urk.py ui compare reference.png capture.png --diff d.png   # rubric score (see visual.py)

`new` copies a built-in screen into <project>/src/shared/UrkScreens/<Name>.json (Rojo makes it a
ModuleScript), sets its id, and writes <project>/src/client/Screens/<Name>.client.luau, a LocalScript
that builds it with Spec/Builder and opens it. Existing files are never overwritten.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import webbrowser
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
from spec_rules import validate  # noqa: E402

SCREENS = ROOT / "library" / "src" / "UI" / "Spec" / "Screens"

BOOTSTRAP = """--!strict
-- Generated by `urk.py ui new {template}`. Builds the {name} screen from its spec and opens it.
-- Edit src/shared/UrkScreens/{name}.json to change the screen; this script rarely needs changes.
local Players = game:GetService("Players")
local ReplicatedStorage = game:GetService("ReplicatedStorage")

local Shared = ReplicatedStorage:WaitForChild("Shared")
local Urk = Shared:WaitForChild("Urk")
local UrkUI = require(Urk:WaitForChild("UI"):WaitForChild("UrkUI"))
local Builder = require(Urk.UI:WaitForChild("Spec"):WaitForChild("Builder"))
local spec = require(Shared:WaitForChild("UrkScreens"):WaitForChild("{name}"))

if not UrkUI.store then
	UrkUI.start({{ store = UrkUI.Store.fromAttributes(Players.LocalPlayer, "Stats") }})
end

local screen = Builder.build(spec, {{ parent = Players.LocalPlayer:WaitForChild("PlayerGui"), store = UrkUI.store }})
screen.Intent:Connect(function(name: string, _args: any, elementId: string?)
	-- Purchases are prompted by Game/PurchaseBridge and granted only on the server (Systems/Shop).
	-- Handle game-specific intents here, e.g. send "Buy" to your server remote.
	print("[{name}]", name, elementId)
end)
screen:open()
"""


def cmd_list(_a):
    for f in sorted(SCREENS.glob("*.json")):
        spec = json.loads(f.read_text())
        print(f"{f.stem:18} {spec.get('kind', '?'):7} {spec.get('description', '')[:90]}")
    return 0


def cmd_validate(a):
    bad = 0
    for p in a.files:
        errors = validate(json.loads(Path(p).read_text()))
        bad += bool(errors)
        print(f"{'FAIL' if errors else 'PASS'} {p}")
        for e in errors:
            print(f"     {e['path'] or '(root)'}: {e['message']}")
    return 1 if bad else 0


def cmd_new(a):
    src = SCREENS / f"{a.template}.json"
    if not src.exists():
        raise SystemExit(f"unknown template {a.template}; see `urk.py ui list`")
    if not re.fullmatch(r"[A-Z][A-Za-z0-9]{1,40}", a.name):
        raise SystemExit("--name must be PascalCase letters and digits, e.g. MyShop")
    project = a.project.expanduser().resolve()
    spec_path = project / "src" / "shared" / "UrkScreens" / f"{a.name}.json"
    script_path = project / "src" / "client" / "Screens" / f"{a.name}.client.luau"
    for p in (spec_path, script_path):
        if p.exists():
            raise SystemExit(f"{p} exists; choose another --name")
    spec = json.loads(src.read_text())
    spec["id"] = a.name
    errors = validate(spec)
    if errors:
        raise SystemExit(f"template invalid: {errors}")
    if not (project / "src" / "shared" / "Urk" / "UI").exists():
        print("note: the UI library is not in this project yet; run `urk.py add UI --project ...` first")
    spec_path.parent.mkdir(parents=True, exist_ok=True)
    script_path.parent.mkdir(parents=True, exist_ok=True)
    spec_path.write_text(json.dumps(spec, indent=2) + "\n")
    script_path.write_text(BOOTSTRAP.format(template=a.template, name=a.name))
    print(f"created {spec_path.relative_to(project)} and {script_path.relative_to(project)}")
    print(f"preview it: python3 urk.py ui preview {spec_path} --open")
    return 0


def cmd_preview(a):
    out = a.out or (ROOT / "build" / "ui" / f"{Path(a.spec).stem}.html")
    code = subprocess.run([sys.executable, str(HERE / "preview_spec.py"), str(a.spec), "-o", str(out)]).returncode
    if code == 0 and a.open:
        webbrowser.open(Path(out).resolve().as_uri())
    return code


def cmd_tokens(a):
    return subprocess.run([sys.executable, str(HERE / "build_tokens.py"), *(["--check"] if a.check else [])]).returncode


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    if argv and argv[0] in ("extract", "compare"):
        # Visual loop tools live in visual.py (needs Pillow); pass straight through.
        return subprocess.run([sys.executable, str(HERE / "visual.py"), *argv]).returncode
    ap = argparse.ArgumentParser(prog="urk.py ui", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("list")
    v = sub.add_parser("validate")
    v.add_argument("files", nargs="+")
    n = sub.add_parser("new")
    n.add_argument("template")
    n.add_argument("--name", required=True)
    n.add_argument("--project", type=Path, required=True)
    p = sub.add_parser("preview")
    p.add_argument("spec")
    p.add_argument("-o", "--out", type=Path)
    p.add_argument("--open", action="store_true")
    t = sub.add_parser("tokens")
    t.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    return {"list": cmd_list, "validate": cmd_validate, "new": cmd_new, "preview": cmd_preview, "tokens": cmd_tokens}[a.cmd](a)


if __name__ == "__main__":
    sys.exit(main())
