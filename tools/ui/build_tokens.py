#!/usr/bin/env python3
"""Generate library/src/UI/Style/StyleTokens.luau from design/tokens/styles.json.

  python3 tools/ui/build_tokens.py          # write
  python3 tools/ui/build_tokens.py --check  # exit 1 if the Luau module is stale (CI)

`extends` is resolved here (deep merge), so the runtime receives complete styles and never
has to merge at startup. Stdlib only.
"""
from __future__ import annotations

import argparse
import copy
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "design" / "tokens" / "styles.json"
OUT = ROOT / "library" / "src" / "UI" / "Style" / "StyleTokens.luau"
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def deep_merge(base, extra):
    out = copy.deepcopy(base)
    for k, v in extra.items():
        out[k] = deep_merge(out[k], v) if isinstance(v, dict) and isinstance(out.get(k), dict) else copy.deepcopy(v)
    return out


def resolve(styles: dict) -> dict:
    done: dict = {}

    def get(name, chain=()):
        if name in done:
            return done[name]
        if name in chain:
            raise SystemExit(f"extends cycle: {' -> '.join(chain + (name,))}")
        raw = styles[name]
        parent = raw.get("extends")
        own = {k: v for k, v in raw.items() if k != "extends"}
        done[name] = deep_merge(get(parent, chain + (name,)), own) if parent else own
        done[name]["name"] = name
        return done[name]

    for n in styles:
        get(n)
    return done


def lua(value, indent=1) -> str:
    pad = "\t" * indent
    if isinstance(value, dict):
        if not value:
            return "{}"
        items = []
        for k in sorted(value):
            key = k if IDENT.match(k) else f'["{k}"]'
            items.append(f"{pad}{key} = {lua(value[k], indent + 1)},")
        return "{\n" + "\n".join(items) + "\n" + "\t" * (indent - 1) + "}"
    if isinstance(value, list):
        return "{ " + ", ".join(lua(v, indent) for v in value) + " }"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    return json.dumps(value)


def render() -> str:
    data = json.loads(SRC.read_text())
    styles = resolve(data["styles"])
    return ("--!strict\n-- Generated by tools/ui/build_tokens.py from design/tokens/styles.json. Do not edit.\n"
            "-- Resolved game styles (extends already merged). Read through Style/Style.luau.\n\n"
            f"return {lua(styles)} :: {{ [string]: any }}\n")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = render()
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"stale: {OUT.relative_to(ROOT)} (run tools/ui/build_tokens.py)")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
