#!/usr/bin/env python3
"""Import an icon pack YOU downloaded into YOUR project, as Roblox sprite sheets and a Luau catalog.

  python3 tools/icons/import_pack.py ~/Downloads/free-icon-pack --pack bbb \\
      --source "https://builtbybit.com/resources/free-icon-pack.54420/" \\
      --license-note "BuiltByBit resource licence: personal/commercial use in my game, no redistribution" \\
      --out ~/games/MyGame/assets/icons/bbb --luau ~/games/MyGame/src/shared/IconPacks/Bbb.luau

Why this exists: many free packs (BuiltByBit, itch.io, marketplaces) allow use inside a game but
not republishing the files, so the kit cannot ship them. You download the pack with your account,
accept its terms, and this script converts it locally. Nothing is uploaded or committed for you.

What it does
- Reads PNG files (recursively). SVG is not rasterised here; export SVGs to PNG first.
- Names: file stem -> lowercase-kebab ("Sword_Icon 02.png" -> "sword-icon-02"); folder names
  become categories; duplicates get -2, -3 suffixes.
- Trims transparent borders, fits each icon into a 128 cell with padding, packs 1024 sheets.
- `--tint white` converts glyphs to white so ImageColor3 can theme them (only for single-colour packs).
- Writes sheet-N.png, icons.json, preview.png, PROVENANCE.md (source, licence note, date, file hashes)
  and a Luau module to pass to IconCatalog.register(...).
- Refuses to write into a folder that already has a different pack, and writes a .gitignore beside
  the files unless --allow-commit is given, because public repositories usually may not contain them.
Needs Pillow.
"""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import re
import sys
from pathlib import Path

try:
    from PIL import Image
except ImportError:  # pragma: no cover
    sys.exit("Pillow is required: python3 -m pip install pillow")

CELL, SHEET, PAD = 128, 1024, 8


def kebab(text: str) -> str:
    text = re.sub(r"([a-z0-9])([A-Z])", r"\1-\2", text)
    text = re.sub(r"[^A-Za-z0-9]+", "-", text).strip("-").lower()
    return text or "icon"


def collect(src: Path):
    files = sorted(p for p in src.rglob("*") if p.suffix.lower() == ".png" and p.is_file())
    if not files:
        raise SystemExit(f"No PNG files under {src}. Export SVG icons to PNG first.")
    seen, out = {}, []
    for f in files:
        base = kebab(f.stem)
        n = seen.get(base, 0) + 1
        seen[base] = n
        name = base if n == 1 else f"{base}-{n}"
        category = kebab(f.parent.name) if f.parent != src else "imported"
        out.append((name, category, f))
    return out


def fit(path: Path, tint: str | None) -> Image.Image:
    img = Image.open(path).convert("RGBA")
    box = img.getchannel("A").getbbox()
    if box:
        img = img.crop(box)
    inner = CELL - 2 * PAD
    scale = min(inner / img.width, inner / img.height)
    img = img.resize((max(1, round(img.width * scale)), max(1, round(img.height * scale))), Image.LANCZOS)
    if tint == "white":
        white = Image.new("RGBA", img.size, (255, 255, 255, 255))
        white.putalpha(img.getchannel("A"))
        img = white
    cell = Image.new("RGBA", (CELL, CELL), (0, 0, 0, 0))
    cell.alpha_composite(img, ((CELL - img.width) // 2, (CELL - img.height) // 2))
    return cell


def luau(pack: str, entries) -> str:
    lines = ["--!strict", f"-- Generated by tools/icons/import_pack.py for pack '{pack}'. See PROVENANCE.md beside the sheets.",
             "-- Usage: IconCatalog.register(require(this)); IconCatalog.configure({ pack = \"%s\", sheets = { ... } })" % pack,
             "", "return {", f'\tpack = "{pack}",', f"\tcell = {CELL},", f"\tpadding = {PAD},", "\ticons = {"]
    for e in entries:
        lines.append(f'\t\t{{ name = "{e["name"]}", category = "{e["category"]}", tags = {{}}, '
                     f'sheet = {e["sheet"]}, x = {e["x"]}, y = {e["y"]}, w = {CELL}, h = {CELL} }},')
    lines += ["\t},", "}", ""]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source_dir", type=Path)
    ap.add_argument("--pack", required=True, help="short id, letters and digits (used as the Luau pack id)")
    ap.add_argument("--source", required=True, help="where you got it (URL)")
    ap.add_argument("--license-note", required=True, help="the licence terms you accepted, in your words")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--luau", type=Path, help="where to write the Luau catalog module")
    ap.add_argument("--prefix", default="", help="prefix every icon name, e.g. 'bbb-' to avoid clashes")
    ap.add_argument("--tint", choices=["white"], help="recolour glyphs to white for theming")
    ap.add_argument("--allow-commit", action="store_true", help="do not write a .gitignore beside the files")
    a = ap.parse_args(argv)
    if not re.fullmatch(r"[a-z][a-z0-9]{1,30}", a.pack):
        raise SystemExit("--pack must be 2-31 lowercase letters/digits, starting with a letter")
    marker = a.out / "icons.json"
    if marker.exists() and json.loads(marker.read_text()).get("pack") != a.pack:
        raise SystemExit(f"{a.out} already holds a different pack; choose another --out")
    a.out.mkdir(parents=True, exist_ok=True)
    items = collect(a.source_dir.expanduser())
    per = (SHEET // CELL) ** 2
    sheets, entries, hashes = [], [], []
    for i, (name, category, path) in enumerate(items):
        s, slot = divmod(i, per)
        if s == len(sheets):
            sheets.append(Image.new("RGBA", (SHEET, SHEET), (0, 0, 0, 0)))
        x, y = (slot % (SHEET // CELL)) * CELL, (slot // (SHEET // CELL)) * CELL
        sheets[s].alpha_composite(fit(path, a.tint), (x, y))
        entries.append({"name": a.prefix + name, "category": category, "sheet": s + 1, "x": x, "y": y,
                        "file": str(path.relative_to(a.source_dir.expanduser()))})
        hashes.append(f"| {a.prefix + name} | `{path.name}` | {hashlib.sha256(path.read_bytes()).hexdigest()[:16]} |")
    for i, sheet in enumerate(sheets, 1):
        sheet.save(a.out / f"sheet-{i}.png", optimize=True)
    preview = Image.new("RGBA", (min(len(entries), 12) * 72, ((len(entries) + 11) // 12) * 72), (32, 35, 42, 255))
    for i, e in enumerate(entries):
        cell = sheets[e["sheet"] - 1].crop((e["x"], e["y"], e["x"] + CELL, e["y"] + CELL)).resize((64, 64), Image.LANCZOS)
        preview.alpha_composite(cell, ((i % 12) * 72 + 4, (i // 12) * 72 + 4))
    preview.save(a.out / "preview.png")
    catalog = {"pack": a.pack, "source": a.source, "licenseNote": a.license_note,
               "imported": dt.date.today().isoformat(), "cell": CELL, "padding": PAD,
               "sheets": [{"file": f"sheet-{i}.png", "assetId": None} for i in range(1, len(sheets) + 1)], "icons": entries}
    marker.write_text(json.dumps(catalog, indent=1) + "\n")
    (a.out / "PROVENANCE.md").write_text(
        f"# Icon pack '{a.pack}'\n\n- Source: {a.source}\n- Licence accepted by the project owner: {a.license_note}\n"
        f"- Imported: {catalog['imported']} with UltimateRobloxKit tools/icons/import_pack.py\n\n"
        "Check the pack's own licence before publishing these files anywhere, including public repositories.\n\n"
        "| Icon | Original file | sha256 (16) |\n|---|---|---|\n" + "\n".join(hashes) + "\n")
    if not a.allow_commit:
        (a.out / ".gitignore").write_text("# Third-party icons: licence may forbid redistribution. Remove only if it allows it.\n*\n!.gitignore\n!PROVENANCE.md\n")
    if a.luau:
        a.luau.parent.mkdir(parents=True, exist_ok=True)
        a.luau.write_text(luau(a.pack, entries))
    print(f"{len(entries)} icons, {len(sheets)} sheet(s) -> {a.out}" + (f"; Luau -> {a.luau}" if a.luau else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
