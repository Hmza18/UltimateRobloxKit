#!/usr/bin/env python3
"""Contact sheet of the generated VFX textures for eyeballing. Stdlib only.

  python3 tools/vfx/preview.py                      # writes build/vfx/preview.html
  python3 tools/vfx/preview.py --out /tmp/vfx.html
  python3 tools/vfx/preview.py --tint "#FFD23F"     # add a tinted row (what ParticleEmitter.Color does)

The page is one self-contained HTML file (PNGs inlined as base64, no network). Each texture is shown
on a dark and a light background, plus a tinted copy; flipbooks also play as an animation. This is a
browser approximation for checking shapes and edges. It does not show how Roblox renders particles
(LightEmission, blending and filtering differ): judge those in Studio.
"""
from __future__ import annotations

import argparse
import base64
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "assets" / "vfx"
DEFAULT_OUT = ROOT / "build" / "vfx" / "preview.html"
GRID = {"Grid2x2": 2, "Grid4x4": 4, "Grid8x8": 8}

CSS = """
body{margin:0;padding:24px;background:#16181d;color:#e8eaf0;font:14px/1.45 system-ui,sans-serif}
h1{font-size:20px;margin:0 0 4px} h2{font-size:15px;margin:28px 0 10px;color:#aab1c5}
p{margin:0 0 6px;color:#aab1c5;max-width:900px}
.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(330px,1fr));gap:12px}
.card{background:#20232b;border:1px solid #31353f;border-radius:8px;padding:10px}
.card b{font-size:14px} .card small{color:#8d95aa} .desc{color:#aab1c5;font-size:12px;margin:4px 0 0}
.row{display:flex;gap:6px;margin-top:8px}
.sw{flex:1;height:96px;border-radius:6px;display:flex;align-items:center;justify-content:center;overflow:hidden}
.sw img,.sw i{max-width:88px;max-height:88px;image-rendering:auto}
.dark{background:#0b0c10} .light{background:#e9ecf2} .mid{background:#3a4254}
.light img{filter:brightness(0)}  /* white art is invisible on white: show its silhouette instead */
.tint{display:block;width:88px;height:88px;background:var(--tint);-webkit-mask:var(--img) center/contain no-repeat;
  mask:var(--img) center/contain no-repeat}
.flip{display:block;width:88px;height:88px;background-image:var(--img);background-size:calc(var(--n)*88px) calc(var(--n)*88px)}
.id{font:12px ui-monospace,monospace;color:#7fd1a0}
"""

JS = """
for (const el of document.querySelectorAll('.flip')) {
  const n = Number(el.dataset.grid), frames = n * n; let f = 0;
  setInterval(() => { el.style.backgroundPosition = `-${(f % n) * 88}px -${Math.floor(f / n) * 88}px`; f = (f + 1) % frames; }, 1000 / 12);
}
"""


def data_uri(path: Path) -> str:
    return "data:image/png;base64," + base64.b64encode(path.read_bytes()).decode("ascii")


def card(item: dict, assets: Path, tint: str) -> str:
    uri = data_uri(assets / item["file"])
    width, height = item["size"]
    meta = f'{width}x{height}, {item["bytes"]} bytes'
    if item["kind"] == "flipbook":
        meta += f', {item["layout"]}, {item["frames"]} frames'
    asset = f'<span class="id">rbxassetid://{item["assetId"]}</span>' if item.get("assetId") else "<small>not uploaded</small>"
    cells = [f'<div class="sw dark"><img alt="{html.escape(item["key"])} on dark" src="{uri}"></div>',
             f'<div class="sw light"><img alt="{html.escape(item["key"])} silhouette on light" src="{uri}"></div>',
             f'<div class="sw mid"><i class="tint" style="--img:url({uri});--tint:{tint}"></i></div>']
    if item["kind"] == "flipbook":
        cells.append(f'<div class="sw dark"><i class="flip" data-grid="{GRID[item["layout"]]}" '
                     f'style="--img:url({uri});--n:{GRID[item["layout"]]}"></i></div>')
    return (f'<div class="card"><b>{html.escape(item["key"])}</b> <small>{meta}</small> {asset}'
            f'<div class="desc">{html.escape(item["description"])}</div><div class="row">{"".join(cells)}</div></div>')


def render(assets: Path = ASSETS, tint: str = "#FFD23F") -> str:
    manifest = json.loads((assets / "manifest.json").read_text(encoding="utf-8"))
    textures, flipbooks = manifest["textures"], manifest["flipbooks"]
    total = sum(i["bytes"] for i in textures + flipbooks)
    parts = ['<!doctype html><html lang="en"><head><meta charset="utf-8"><title>URK VFX textures</title>',
             f"<style>{CSS}</style></head><body><h1>URK VFX textures</h1>",
             f"<p>{len(textures)} textures and {len(flipbooks)} flipbooks, {total} bytes in total. Generated by "
             "tools/vfx/textures.py; original work, MIT. Columns: on dark, silhouette on light, tinted"
             f" {html.escape(tint)}; flipbooks also play at 12 fps.</p>",
             "<p>Browser approximation only. Particle blending and filtering are judged in Roblox Studio.</p>",
             '<h2>Textures</h2><div class="grid">', "".join(card(i, assets, tint) for i in textures), "</div>",
             '<h2>Flipbooks</h2><div class="grid">', "".join(card(i, assets, tint) for i in flipbooks), "</div>",
             f"<script>{JS}</script></body></html>\n"]
    return "".join(parts)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT, help="HTML file to write (default build/vfx/preview.html)")
    ap.add_argument("--assets", type=Path, default=ASSETS, help="folder holding manifest.json (default assets/vfx)")
    ap.add_argument("--tint", default="#FFD23F", help="colour of the tinted column, #RRGGBB")
    a = ap.parse_args(argv)
    if not re.match(r"^#[0-9A-Fa-f]{6}$", a.tint):
        print(f"--tint must be #RRGGBB, got {a.tint}", file=sys.stderr)
        return 2
    if not (a.assets / "manifest.json").exists():
        print(f"no manifest in {a.assets}: run python3 tools/vfx/textures.py first", file=sys.stderr)
        return 1
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(render(a.assets, a.tint), encoding="utf-8")
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
