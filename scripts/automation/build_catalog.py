#!/usr/bin/env python3
"""Regenerate catalog/skills.json, the router's skill index and docs/references/skill-catalog.md.

  python3 scripts/automation/build_catalog.py          # write
  python3 scripts/automation/build_catalog.py --check  # exit 1 if anything is stale (CI)
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from lib.env import KIT_ROOT  # noqa: E402
from lib.skills import discover  # noqa: E402

ROUTER = KIT_ROOT / "skills/orchestration/roblox-kit-router/SKILL.md"
DOC = KIT_ROOT / "docs/references/skill-catalog.md"
JSON = KIT_ROOT / "catalog/skills.json"
START, END = "<!-- CATALOG:START -->", "<!-- CATALOG:END -->"


def short(desc: str) -> str:
    first = desc.split(". ")[0].rstrip(".")
    return first if len(first) <= 150 else first[:147].rsplit(" ", 1)[0] + "..."


def render(skills):
    by_cat = {}
    for s in skills.values():
        by_cat.setdefault(s["category"], []).append(s)
    index = []
    for cat in sorted(by_cat):
        index.append(f"**{cat}**")
        index.append("")
        for s in sorted(by_cat[cat], key=lambda x: x["name"]):
            index.append(f"- `{s['name']}`: {short(s['description'])}")
        index.append("")
    doc = ["# Skill catalog", "", f"{len(skills)} skills. Generated by `scripts/automation/build_catalog.py`; do not edit by hand.", ""]
    for cat in sorted(by_cat):
        doc += [f"## {cat}", "", "| Skill | What it does | Depends on |", "|---|---|---|"]
        for s in sorted(by_cat[cat], key=lambda x: x["name"]):
            link = f"[`{s['name']}`](../../{s['path']}/SKILL.md)"
            doc.append(f"| {link} | {s['description'].replace('|', '/')} | {', '.join(s['depends']) or '-'} |")
        doc.append("")
    data = {"version": 1, "skills": [{k: s[k] for k in ("name", "category", "path", "description", "triggers", "depends")}
                                     for s in sorted(skills.values(), key=lambda x: x["name"])]}
    return "\n".join(index).rstrip() + "\n", "\n".join(doc), json.dumps(data, indent=1) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    skills = discover()
    index, doc, data = render(skills)
    router = ROUTER.read_text()
    head, rest = router.split(START, 1)
    _, tail = rest.split(END, 1)
    new_router = f"{head}{START}\n{index}{END}{tail}"
    targets = {ROUTER: new_router, DOC: doc, JSON: data}
    stale = [p for p, text in targets.items() if not p.exists() or p.read_text() != text]
    if a.check:
        for p in stale:
            print(f"stale: {p.relative_to(KIT_ROOT)} (run scripts/automation/build_catalog.py)")
        return 1 if stale else 0
    for p, text in targets.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    print(f"catalog: {len(skills)} skills")
    return 0


if __name__ == "__main__":
    sys.exit(main())
