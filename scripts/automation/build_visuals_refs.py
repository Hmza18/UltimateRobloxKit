#!/usr/bin/env python3
"""Regenerate the preset tables that skills and docs show, from catalog/visuals.json.

  python3 scripts/automation/build_visuals_refs.py          # write
  python3 scripts/automation/build_visuals_refs.py --check  # exit 1 if anything is stale (tests, CI)

catalog/visuals.json is itself generated from the pure Luau modules:
  cd library && lune run tools/export_visuals
Run that first after adding or changing a preset, then this script. Standard library only.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from lib.env import KIT_ROOT  # noqa: E402

CATALOG = KIT_ROOT / "catalog/visuals.json"
SKILLS = KIT_ROOT / "skills/visuals"
NOTE = ("Generated by `scripts/automation/build_visuals_refs.py` from `catalog/visuals.json`; do not edit by hand. "
        "The JSON is the source of truth and also holds every parameter's type, default and range.")

KIND_TITLES = {
    "vfx": ("World VFX", 'Visuals:Play(id, at, params?)` / `Visuals:Attach(id, target, params?)'),
    "ui": ("UI animations", "Visuals.UI.animate(gui, id, options?)"),
    "object": ("Object animations", "Visuals.Objects.animate(target, id, options?)"),
    "camera": ("Camera", "Visuals.Camera.shake(id)` / `Visuals.Camera.cinematic(id, target)"),
    "pet": ("Pet reactions and timelines", "Visuals.Pets.play(id, model, options?)"),
    "rarity": ("Rarity profiles", "Visuals.Rewards.reveal(id, reward, options?)"),
    "feedback": ("Feedback events", "Visuals.Feedback.fire(id, context?)"),
    "audio": ("Audio cues", "Visuals.Audio.register(id, soundId)"),
    "theme": ("Themes", 'Visuals:Configure({ theme = id })'),
    "component": ("UI/Game components", "Game.<Name>.new(props)"),
    "screen": ("Screens", "Visuals.Screens"),
}
ORDER = ["vfx", "ui", "object", "camera", "pet", "rarity", "feedback", "audio", "theme", "component", "screen"]


def cell(text) -> str:
    return str(text).replace("|", "/").replace("\n", " ")


def extra_params(item, common=("color", "scale", "intensity", "speed", "delay")) -> str:
    names = sorted(n for n in item["params"] if n not in common)
    out = []
    for n in names:
        p = item["params"][n]
        out.append(f"`{n}` ({', '.join(p['options'])})" if p.get("options") else f"`{n}`")
    return ", ".join(out) or "-"


def by_category(items):
    cats = {}
    for i in items:
        cats.setdefault(i["category"], []).append(i)
    return cats


def kinds_in_order(data):
    return [k for k in ORDER if k in data["kinds"]] + sorted(k for k in data["kinds"] if k not in ORDER)


def preset_index(data) -> str:
    lines = ["# UVK preset index", "", NOTE, "",
             f"{data['total']} entries. Look an id up in `catalog/visuals.json` for its description, params and usage line.", ""]
    lines += ["| Kind | Count | Call |", "|---|---|---|"]
    for kind in kinds_in_order(data):
        title, call = KIND_TITLES.get(kind, (kind, ""))
        lines.append(f"| `{kind}` ({title}) | {len(data['kinds'][kind])} | `{call}` |")
    lines.append("")
    for kind in kinds_in_order(data):
        title, _ = KIND_TITLES.get(kind, (kind, ""))
        lines += [f"## {title} (`{kind}`)", ""]
        cats = by_category(data["kinds"][kind])
        if len(cats) == 1:
            lines += [", ".join(i["id"] for i in data["kinds"][kind]), ""]
            continue
        lines += ["| Category | Ids |", "|---|---|"]
        for cat in sorted(cats):
            lines.append(f"| {cat} ({len(cats[cat])}) | {', '.join(i['id'] for i in cats[cat])} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def vfx_table(data) -> str:
    items = data["kinds"]["vfx"]
    lines = ["# VFX presets", "", NOTE, "",
             f"{len(items)} presets. Every preset also takes `color`, `scale` and `intensity`. "
             "Cost is the label computed from the definition (low, medium, high); keep high-cost presets for rare moments.", ""]
    cats = by_category(items)
    for cat in sorted(cats):
        lines += [f"## {cat} ({len(cats[cat])})", "", "| Id | Cost | Extra params | What it shows |", "|---|---|---|---|"]
        for i in cats[cat]:
            lines.append(f"| `{i['id']}` | {i['quality']['cost']} | {extra_params(i)} | {cell(i['description'])} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def ui_table(data) -> str:
    items = data["kinds"]["ui"]
    lines = ["# UI animation presets", "", NOTE, "",
             f"{len(items)} presets for `Visuals.UI.animate(gui, id, options?)`. Every preset takes `intensity`, `speed` and `delay`.", ""]
    cats = by_category(items)
    for cat in sorted(cats):
        lines += [f"## {cat} ({len(cats[cat])})", "", "| Id | What it does |", "|---|---|"]
        for i in cats[cat]:
            lines.append(f"| `{i['id']}` | {cell(i['description'])} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def feedback_table(data) -> str:
    items = data["kinds"]["feedback"]
    lines = ["# Feedback events", "", NOTE, "",
             f"{len(items)} events across the built-in packs. `Pack` is the pack that first defines the event; "
             "`Also in` lists packs that replace its recipe. Steps are `kind:preset`. Context lists the `$fields` the recipe reads.", "",
             "| Event | Pack | Also in | Steps | Context fields |", "|---|---|---|---|---|"]
    for i in items:
        lines.append(f"| `{i['id']}` | {i['category']} | {', '.join(i['overriddenBy']) or '-'} | {', '.join(i['steps'])} | "
                     f"{', '.join(i['context']) or '-'} |")
    return "\n".join(lines) + "\n"


def rarity_table(data) -> str:
    items = data["kinds"]["rarity"]
    lines = ["# Rarity profiles", "", NOTE, "",
             "Built-in profiles in rank order. Duration is the time to the settled state.", "",
             "| Rarity | Colour | Reveal | Background | Duration | Anticipation | Rays | Flash | Layers | Camera | VFX | Sound cues |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for i in items:
        lines.append(f"| `{i['id']}` | `{i['color']}` | {i['revealStyle']} | {i['background']} | {i['duration']} s | "
                     f"{i['anticipation']} s | {i['rays']} | {i['flash']} | {i['layers']} | {', '.join(i['camera']) or '-'} | "
                     f"{', '.join(i['vfx'])} | {', '.join(i['sounds'])} |")
    return "\n".join(lines) + "\n"


def generic_table(items) -> list:
    lines = ["| Id | Category | Cost | Params | Description |", "|---|---|---|---|---|"]
    for i in items:
        lines.append(f"| `{i['id']}` | {i['category']} | {i['quality']['cost']} | {extra_params(i, common=())} | {cell(i['description'])} |")
    return lines


def docs_page(data) -> str:
    lines = ["# UVK preset reference", "", NOTE, "",
             f"{data['total']} entries in {len(data['kinds'])} kinds. Functions are documented in [visuals-api.md](visuals-api.md).", "",
             "| Kind | Count | Call |", "|---|---|---|"]
    for kind in kinds_in_order(data):
        title, call = KIND_TITLES.get(kind, (kind, ""))
        lines.append(f"| {title} (`{kind}`) | {len(data['kinds'][kind])} | `{call}` |")
    lines += ["", "## Quality profiles", "",
              "| Level | Max particles | Max effects | Max lights | Max distance | Particle scale | Trails | Lights | Highlights | Post-processing | UI shine | Max popups |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    yes = lambda v: "yes" if v else "no"  # noqa: E731
    for level in ("Low", "Medium", "High", "Ultra"):
        q = data["quality"][level]
        lines.append(f"| {level} | {q['maxParticles']} | {q['maxEffects']} | {q['maxLights']} | {q['maxDistance']} | {q['particleScale']} | "
                     f"{yes(q['trails'])} | {yes(q['lights'])} | {yes(q['highlights'])} | {yes(q['postProcessing'])} | {yes(q['uiShine'])} | {q['maxPopups']} |")
    lines.append("")
    for kind in kinds_in_order(data):
        title, _ = KIND_TITLES.get(kind, (kind, ""))
        items = data["kinds"][kind]
        lines += [f"## {title} ({len(items)})", ""]
        if kind == "rarity":
            lines += rarity_table(data).split("\n")[6:]
        elif kind == "feedback":
            lines += feedback_table(data).split("\n")[6:]
        elif kind == "audio":
            groups = by_category(items)
            lines += ["No sounds are bundled; a cue is silent until the game registers a sound for it.", "",
                      "| Group | Cues |", "|---|---|"]
            lines += [f"| {g} | {', '.join('`' + i['id'] + '`' for i in groups[g])} |" for g in sorted(groups)]
            lines.append("")
        elif kind in ("theme", "component"):
            lines += ["| Id | Description |", "|---|---|"]
            lines += [f"| `{i['id']}` | {cell(i['description'])} |" for i in items]
            lines.append("")
        else:
            lines += generic_table(items)
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def targets(data) -> dict:
    return {
        SKILLS / "uvk-visuals-kit/references/preset-index.md": preset_index(data),
        SKILLS / "uvk-vfx-presets/references/vfx-presets.md": vfx_table(data),
        SKILLS / "uvk-ui-animation/references/ui-presets.md": ui_table(data),
        SKILLS / "uvk-gameplay-feedback/references/feedback-events.md": feedback_table(data),
        SKILLS / "uvk-reward-reveals/references/rarity-profiles.md": rarity_table(data),
        KIT_ROOT / "docs/references/visuals-presets.md": docs_page(data),
    }


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    data = json.loads(CATALOG.read_text(encoding="utf-8"))
    out = targets(data)
    stale = [p for p, text in out.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if a.check:
        for p in stale:
            print(f"stale: {p.relative_to(KIT_ROOT)} (run scripts/automation/build_visuals_refs.py)")
        return 1 if stale else 0
    for p, text in out.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    print(f"visuals references: {len(out)} files from {data['total']} catalog entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
